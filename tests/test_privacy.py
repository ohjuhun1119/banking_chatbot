import pytest

from app.privacy import mask_pii


@pytest.mark.parametrize("raw, masked, kind", [
    ("주민등록번호 900101-1234567 입니다", "주민등록번호 [주민등록번호] 입니다", "주민등록번호"),
    ("주민번호 9001011234567로 조회", "주민번호 [주민등록번호]로 조회", "주민등록번호"),
    ("카드 1234-5678-9012-3456 분실", "카드 [카드번호] 분실", "카드번호"),
    ("연락처는 010-1234-5678이에요", "연락처는 [전화번호]이에요", "전화번호"),
    ("02-123-4567로 전화 주세요", "[전화번호]로 전화 주세요", "전화번호"),
    ("메일은 hong@example.com 입니다", "메일은 [이메일] 입니다", "이메일"),
    ("계좌 110-123-456789로 보냈어요", "계좌 [계좌번호]로 보냈어요", "계좌번호"),
    ("계좌번호 12345678901234 입니다", "계좌번호 [계좌번호] 입니다", "계좌번호"),
    ("OTP 번호는 123456 입니다", "OTP 번호는 [비밀정보] 입니다", "비밀정보"),
    ("인증번호: 482913", "인증번호: [비밀정보]", "비밀정보"),
    ("비밀번호 1234 틀렸어요", "비밀번호 [비밀정보] 틀렸어요", "비밀정보"),
])
def test_개인정보를_가림(raw, masked, kind):
    result, found = mask_pii(raw)
    assert result == masked and found.get(kind, 0) >= 1


@pytest.mark.parametrize("text", [
    "환전 신청은 어떻게 하나요?",
    "2026-10-15에 만기예요",                  # 날짜
    "1,000,000원을 이체하고 싶어요",           # 금액
    "100000000원 대출 가능한가요?",            # 9자리 금액
    "대출 3년 만기 연장 서류가 뭐예요?",
    "상담원이랑 통화하고 싶어요",
])
def test_일반_문장은_그대로(text):
    result, found = mask_pii(text)
    assert result == text and found == {}


def test_여러_종류가_함께_있어도_각각_가림():
    result, found = mask_pii("주민번호 900101-1234567이랑 OTP 번호 123456 알려드릴 테니 010-1111-2222로 연락해 주세요")
    assert "900101" not in result and "123456" not in result and "1111" not in result
    assert found == {"주민등록번호": 1, "전화번호": 1, "비밀정보": 1}
